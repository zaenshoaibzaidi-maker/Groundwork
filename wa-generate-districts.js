#!/usr/bin/env node
// wa-generate-districts.js
// Reads wa-districts.js (already contains Census + election data merged by
// wa-fetch-all.js) and regenerates wa-districts.js in place, structured
// identically to ok-districts.js.
//
// Washington's 49 House districts each elect two separate single-winner
// seats (Representative Pos. 1 and Pos. 2) from the same district geography,
// so each seat becomes its own entry ("wa-hd-N-pos1" / "wa-hd-N-pos2").
// Senate districts are standard single-winner ("wa-sd-N").
//
// Usage: node wa-generate-districts.js
// Output: wa-districts.js (created/overwritten in the same directory)

'use strict';

const fs   = require('fs');
const path = require('path');
const vm   = require('vm');

const FILE = path.join(__dirname, 'wa-districts.js');

if (!fs.existsSync(FILE)) {
  console.error('wa-districts.js not found. Run wa-fetch-all.js first.');
  process.exit(1);
}

const source = fs.readFileSync(FILE, 'utf8');
const sandbox = {};
// `const` at top level doesn't land on the sandbox's global object inside
// vm.runInNewContext, so swap to `var` purely for this execution pass.
vm.runInNewContext(source.replace(/^const /gm, 'var '), sandbox);

const houseSource  = sandbox.WA_HOUSE_DISTRICTS;
const senateSource = sandbox.WA_SENATE_DISTRICTS;

if (!Array.isArray(houseSource) || !Array.isArray(senateSource)) {
  console.error('wa-districts.js did not export WA_HOUSE_DISTRICTS / WA_SENATE_DISTRICTS arrays.');
  process.exit(1);
}

// ── render ───────────────────────────────────────────────────────────────────
// Renders a previously-merged entry verbatim, only normalizing the `id`
// field to the canonical scheme — the dashboard payload (stats, demos,
// dem/rep, partisanSub, incumbent fields) is already fully derived from
// Census + election data and is reused as-is.

function renderEntry(entry, id) {
  const d = entry.dashboard || {};
  const stats = d.stats || [];
  const demos = d.demos || [];
  const statValue = (idx) => JSON.stringify(stats[idx] ? stats[idx].value : 'N/A');

  const demosBlock = demos
    .map((e) => `        { label: "${e.label}", pct: ${e.pct}, color: ${JSON.stringify(e.color)} }`)
    .join(',\n');

  return `  {
    id: "${id}",
    name: ${JSON.stringify(entry.name)},
    type: "${entry.type}",
    incumbentName: ${JSON.stringify(entry.incumbentName)},
    incumbentParty: ${JSON.stringify(entry.incumbentParty)},
    nextElection: "November 2026",
    seatStatus: "Active",
    dashboard: {
      subtitle: ${JSON.stringify(d.subtitle)},
      chips: [],
      stats: [
        { label: "Median Household Income", value: ${statValue(0)}, sub: "" },
        { label: "College-Educated Adults",  value: ${statValue(1)},  sub: "" },
        { label: "Median Age",               value: ${statValue(2)},   sub: "" },
        { label: "Renter Rate",              value: ${statValue(3)}, sub: "" }
      ],
      dem: ${d.dem}, rep: ${d.rep},
      partisanSub: ${JSON.stringify(d.partisanSub)},
      demos: [
${demosBlock}
      ],
      issues: [],
      memoHeadline: "",
      memoParagraphs: [],
      memoBullets: []
    }
  }`;
}

// ── reassign canonical ids by position in array ─────────────────────────────
// House entries were written in district order, alternating Pos. 1 / Pos. 2.

const houseEntries = houseSource.map((entry, i) => {
  const district = Math.floor(i / 2) + 1;
  const pos = (i % 2) + 1;
  return renderEntry(entry, `wa-hd-${district}-pos${pos}`);
});

const senateEntries = senateSource.map((entry, i) => {
  const district = i + 1;
  return renderEntry(entry, `wa-sd-${district}`);
});

// ── build output ─────────────────────────────────────────────────────────────

const output = `/* wa-districts.js — Groundwork Washington District Data
 *
 * Generated by wa-generate-districts.js from wa-districts.js (Census +
 * election data merged by wa-fetch-all.js).
 * Census: ACS 5-Year 2023 (2019–2023) | Elections: 2024/2022 General (WA SoS)
 * ─────────────────────────────────────────────────────────────────────── */

const DEMO_COLORS = ['#4e9e68','#2563eb','#f59e0b','#ef4444'];

const WA_HOUSE_DISTRICTS = [
${houseEntries.join(',\n')}
];

const WA_SENATE_DISTRICTS = [
${senateEntries.join(',\n')}
];
`;

fs.writeFileSync(FILE, output);

console.log(`Written → ${FILE}`);
console.log(`  House districts:  ${houseEntries.length}`);
console.log(`  Senate districts: ${senateEntries.length}`);
