function toResults(data) {
  const out = {};
  for (const [district, [winner, party, pct]] of Object.entries(data)) {
    out[district] = { winner, party, pct, unopposed: pct === null };
  }
  return out;
}

function main() {
  const output = {
    house: toResults(HOUSE_DATA),
    senate: toResults(SENATE_DATA),
  };

  fs.writeFileSync(path.join(__dirname, 'ma-elections-data.json'), JSON.stringify(output, null, 2));

  console.log(`Senate districts: ${Object.keys(output.senate).length}`);
  console.log(`House districts:  ${Object.keys(output.house).length}`);
  console.log('Written to ma-elections-data.json');
}

main();
