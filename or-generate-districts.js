#!/usr/bin/env node
// or-generate-districts.js
// Reads or-districts.js (already fully built by or-fetch-all.js, which
// merges Census + election data and writes the formatted dashboard objects
// directly -- there is no intermediate or-all-districts-data.json the way
// other states have) and re-emits OR_HOUSE_DISTRICTS / OR_SENATE_DISTRICTS
// through the same string-template structure ok-generate-districts.js uses,
// overwriting or-districts.js in place. This is an idempotent normalization
// pass: no new data is computed, it just guarantees the file's structure
// matches the standard template exactly (chips/issues/memo* placeholders,
// demos color-by-position, etc).
//
// Usage: node or-generate-districts.js
// Output: or-districts.js (overwritten in place)

'use strict';

const fs   = require('fs');
const path = require('path');

const TARGET = path.join(__dirname, 'or-districts.js');

if (!fs.existsSync(TARGET)) {
  console.error('or-districts.js not found. Run or-fetch-all.js first.');
  process.exit(1);
}

// or-districts.js declares `const OR_HOUSE_DISTRICTS = [...]` /
// `const OR_SENATE_DISTRICTS = [...]` rather than exporting them, so load it
// via a throwaway copy with an appended module.exports.
const SCRATCH = path.join(
  '/private/tmp/claude-501/-Users-zzaidi-GroundWork/b7fe3e13-f226-4774-83d9-3c5a60156369/scratchpad',
  'or-districts-loader.js'
);
const source = fs.readFileSync(TARGET, 'utf8');
fs.writeFileSync(SCRATCH, `${source}\nmodule.exports = { OR_HOUSE_DISTRICTS, OR_SENATE_DISTRICTS };\n`);
delete require.cache[require.resolve(SCRATCH)];
const { OR_HOUSE_DISTRICTS, OR_SENATE_DISTRICTS } = require(SCRATCH);

// ── helpers ───────────────────────────────────────────────────────────────────

function formatStat(s) {
  return `        { label: ${JSON.stringify(s.label)}, value: ${JSON.stringify(s.value)}, sub: ${JSON.stringify(s.sub || '')} }`;
}

function formatDemos(demos) {
  if (!demos || !demos.length) return '';
  return demos
    .map((d, i) => `        { label: "${d.label}", pct: ${Number(d.pct).toFixed(2)}, color: DEMO_COLORS[${i}] }`)
    .join(',\n');
}

function renderEntry(entry) {
  const dash = entry.dashboard;
  return `  {
    id: ${JSON.stringify(entry.id)},
    name: ${JSON.stringify(entry.name)},
    type: ${JSON.stringify(entry.type)},
    incumbentName: ${JSON.stringify(entry.incumbentName)},
    incumbentParty: ${JSON.stringify(entry.incumbentParty)},
    nextElection: ${JSON.stringify(entry.nextElection)},
    seatStatus: ${JSON.stringify(entry.seatStatus)},
    dashboard: {
      subtitle: ${JSON.stringify(dash.subtitle)},
      chips: [],
      stats: [
${dash.stats.map(formatStat).join(',\n')}
      ],
      dem: ${dash.dem}, rep: ${dash.rep},
      partisanSub: ${JSON.stringify(dash.partisanSub)},
      demos: [
${formatDemos(dash.demos)}
      ],
      issues: [],
      memoHeadline: "",
      memoParagraphs: [],
      memoBullets: []
    }
  }`;
}

function findOrThrow(entries, id) {
  const entry = entries.find((e) => e.id === id);
  if (!entry) throw new Error(`missing district entry: ${id}`);
  return entry;
}

// ── build output ──────────────────────────────────────────────────────────────

const houseEntries = [];
for (let i = 1; i <= 60; i++) {
  houseEntries.push(renderEntry(findOrThrow(OR_HOUSE_DISTRICTS, `or-hd-${i}`)));
}

const senateEntries = [];
for (let i = 1; i <= 30; i++) {
  senateEntries.push(renderEntry(findOrThrow(OR_SENATE_DISTRICTS, `or-sd-${i}`)));
}

const output = `/* or-districts.js — Groundwork Oregon District Data
 *
 * Generated by or-generate-districts.js from or-districts.js.
 * Census: ACS 5-Year 2023 (2019–2023) | Elections: 2024/2022 General (OR SoS)
 * ─────────────────────────────────────────────────────────────────────── */

const DEMO_COLORS = ['#4e9e68','#2563eb','#f59e0b','#ef4444'];

const OR_HOUSE_DISTRICTS = [
${houseEntries.join(',\n')}
];

const OR_SENATE_DISTRICTS = [
${senateEntries.join(',\n')}
];
`;

fs.writeFileSync(TARGET, output);
fs.unlinkSync(SCRATCH);

console.log(`Written → ${TARGET}`);
console.log(`  House districts:  ${houseEntries.length}`);
console.log(`  Senate districts: ${senateEntries.length}`);
